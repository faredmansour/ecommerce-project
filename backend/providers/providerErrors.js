class PaymentProviderError extends Error {
  constructor(code, message, { provider = null, operation = null } = {}) {
    super(message);
    this.name = "PaymentProviderError";
    this.code = code;
    this.provider = provider;
    this.operation = operation;
    this.retryable = false;
    this.outcome = "unknown";
    this.isOperational = true;
  }
}

const SAFE_PROVIDER_ERROR_CODES = new Set([
  ...Object.values(PROVIDER_ERROR_CODES),
  "PROVIDER_REJECTED",
  "INVALID_PROVIDER_RESPONSE",
  "PROVIDER_UNKNOWN_ERROR",
]);

function providerDeferred(provider, operation) {
  return new PaymentProviderError(
    PROVIDER_ERROR_CODES.OPERATION_DEFERRED,
    `The ${provider} ${operation} operation is deferred and cannot contact a provider.`,
    { provider, operation }
  );
}

module.exports = { PROVIDER_ERROR_CODES, SAFE_PROVIDER_ERROR_CODES, PaymentProviderError, providerDeferred };
